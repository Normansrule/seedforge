#!/usr/bin/env python3
"""Regenerate every SeedForge CAD output from editable source, then run CAD QA.

    python tools/build_cad.py            # full build + interference sweep (~5 min)
    python tools/build_cad.py --fast     # skip the core-cell interference sweep
    python tools/build_cad.py --qa-only  # only re-run QA on existing files

Sources of truth (see hardware/cad/README.md):
  hardware/cad/step/machine/*.step   R3 machine parts (their generator was not in the R3 package)
  hardware/cad/source/core_cell.py   R3.1 parts W09-W14, F08-F11 + core-cell layout
  hardware/cad/source/paper_reference.py   MR/PR reference models
  hardware/cad/source/assemblies.py  viewer arrangements
Generated: stl/, 3mf/, glb/, manifest.csv, manifest.json, QA_REPORT.md
"""
from __future__ import annotations

import argparse
import csv
import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "hardware" / "cad" / "source"
sys.path.insert(0, str(SRC))

import trimesh  # noqa: E402

from sf_cad_common import CAD_ROOT, export_part, load_step, write_glb, PALETTE  # noqa: E402
from part_catalog import PARTS, catalog_row  # noqa: E402

A1_MINI = (180.0, 180.0, 180.0)
PETG_G_CM3 = 1.27


def convert_r3_parts():
    """R3 STEP originals (hardware/cad/source/r3_step) -> M2-only STEP in step/machine."""
    import m2_fasteners
    src = SRC / "r3_step"
    log = []
    for step in sorted(src.glob("*.step")):
        changes = m2_fasteners.convert_file(step, CAD_ROOT / "step" / "machine" / step.name, step.stem[:3])
        if changes:
            log.append((step.stem, len(changes)))
    (CAD_ROOT / "m2_conversion_log.json").write_text(json.dumps(
        {"rule": "M3 clearance 3.4 -> 2.4, M3 pilot 2.9 -> 1.8, plus per-part rules in m2_fasteners.py",
         "parts": {k: v for k, v in log}}, indent=1) + "\n")
    return len(log)


def regenerate_machine_meshes():
    """STL + 3MF for R3 parts, tessellated from their STEP."""
    n = 0
    for step in sorted((CAD_ROOT / "step" / "machine").glob("*.step")):
        stem = step.stem
        if stem in PARTS and not PARTS[stem]["source"].startswith("R3 STEP"):
            continue                       # generated by core_cell.py
        export_part(load_step(step), stem, "machine", write_step_file=False)
        n += 1
    return n


def fits(ext, env=A1_MINI):
    e = sorted(ext)
    return all(a <= b for a, b in zip(e, sorted(env)))


def qa():
    rows = []
    for family in ("machine", "reference"):
        for stl in sorted((CAD_ROOT / "stl" / family).glob("*.stl")):
            stem = stl.stem
            mesh = trimesh.load_mesh(stl, process=True)
            bodies = len(mesh.split(only_watertight=False))
            ext = [float(v) for v in mesh.extents]
            vol = float(mesh.volume) / 1000.0
            meta = catalog_row(stem, family)
            row = {
                "part_id": meta["id"], "file_stem": stem, "family": family, "module": meta["module"],
                "status": meta["status"], "source": meta["source"], "qty": meta["qty"], "material": meta["material"],
                "bbox_x_mm": round(ext[0], 2), "bbox_y_mm": round(ext[1], 2), "bbox_z_mm": round(ext[2], 2),
                "volume_cm3": round(vol, 3), "watertight": bool(mesh.is_watertight),
                "winding_consistent": bool(mesh.is_winding_consistent), "bodies": bodies,
                "fits_a1_mini": fits(ext), "solid_mass_petg_g": round(vol * PETG_G_CM3, 1),
                "step": f"step/{family}/{stem}.step", "stl": f"stl/{family}/{stem}.stl", "3mf": f"3mf/{family}/{stem}.3mf",
                "cad_valid": None, "print_successful": "not recorded", "physically_fits": "not tested",
                "mechanism_works": "not tested", "process_validated": "no", "notes": meta["notes"],
            }
            checks = [vol > 0, min(ext) > 0, row["watertight"], row["winding_consistent"]]
            if family == "machine":
                checks.append(row["fits_a1_mini"])
                checks.append(max(ext) < 1000)        # catches inch/metre unit mistakes
            row["cad_valid"] = all(checks)
            rows.append(row)
    return rows


def write_manifest(rows):
    out = CAD_ROOT / "manifest.csv"
    with out.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    (CAD_ROOT / "manifest.json").write_text(json.dumps(rows, indent=1) + "\n")


def write_report(rows, layout):
    mach = [r for r in rows if r["family"] == "machine"]
    ref = [r for r in rows if r["family"] == "reference"]
    bad = [r for r in mach if not r["cad_valid"]]
    multi = [r for r in mach if r["bodies"] > 1]
    lines = [
        "# CAD QA report", "",
        "Generated by `python tools/build_cad.py`. Do not edit by hand.", "",
        "**What this report can and cannot say.** `cad_valid` means: positive volume, non-zero size, watertight and",
        "consistently wound mesh, millimetre-plausible size and (machine parts) fits the Bambu Lab A1 Mini",
        "180 x 180 x 180 mm envelope. It does **not** mean the part has been printed, that it fits its purchased",
        "parts, that the mechanism works, or that the process is validated. Those columns stay",
        "`not recorded` / `not tested` until someone fills them in from a real build.", "",
        f"* Machine/tooling parts: **{len(mach)}** ({sum(1 for r in mach if r['cad_valid'])} CAD-valid, {len(bad)} failing)",
        f"* Reference models: **{len(ref)}** ({sum(1 for r in ref if r['watertight'])} watertight)",
        f"* Machine parts with more than one disconnected body: {', '.join(r['part_id'] for r in multi) or 'none'}", "",
    ]
    if layout:
        lines += ["## Core-cell interference check (R3.1 layout)", "",
                  f"* Static interference between fixed parts: **{len(layout.get('static_interference', []))} pairs**",
                  "* Collision-free carriage-centre window (x, mm) by guide angle, sampled every 5 mm:", "",
                  "| guide angle (deg) | carriage x window (mm) |", "|---|---|"]
        for ang, win in sorted(layout.get("collision_free_carriage_window_mm", {}).items(), key=lambda kv: float(kv[0])):
            lines.append(f"| {float(ang):+.0f} | {win[0]} - {win[1]} |" if win else f"| {float(ang):+.0f} | none |")
        lines += ["", "Home trips at carriage x = 45 mm (firmware position 0). The checker intersects solid models of the",
                  "printed parts and nominal purchased-part proxies; real purchased parts may differ - MEASURE BEFORE FINAL FABRICATION.", ""]
    lines += ["## Parts", "", "| id | status | module | qty | bbox mm | vol cm3 | watertight | bodies | A1 Mini | CAD valid |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['part_id']} | {r['status']} | {r['module']} | {r['qty']} | {r['bbox_x_mm']} x {r['bbox_y_mm']} x {r['bbox_z_mm']} | "
                     f"{r['volume_cm3']} | {'yes' if r['watertight'] else 'NO'} | {r['bodies']} | {'yes' if r['fits_a1_mini'] else 'no'} | "
                     f"{'yes' if r['cad_valid'] else ('n/a' if r['family'] == 'reference' else 'NO')} |")
    (CAD_ROOT / "QA_REPORT.md").write_text("\n".join(lines) + "\n")


def part_glbs():
    """Small per-part GLBs for the website module explorer."""
    out = CAD_ROOT / "glb" / "parts"
    out.mkdir(parents=True, exist_ok=True)
    for stl in sorted((CAD_ROOT / "stl" / "machine").glob("*.stl")):
        mesh = trimesh.load_mesh(stl, process=True)
        colour = PALETTE["printed_accent"] if not PARTS.get(stl.stem, {}).get("source", "R3 STEP").startswith("R3 STEP") else PALETTE["printed"]
        write_glb([(stl.stem, mesh, colour)], out / f"{stl.stem.split('_')[0]}.glb")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--qa-only", action="store_true")
    args = ap.parse_args()
    t0 = time.time()
    layout = None
    if not args.qa_only:
        import paper_reference, core_cell, assemblies   # noqa: E401
        print("R3 parts converted to M2 fasteners:", convert_r3_parts())
        print("R3 machine meshes:", regenerate_machine_meshes())
        paper_reference.main()
        print("reference models regenerated")
        layout = core_cell.main(run_checks=not args.fast)
        print("core cell built", "(interference sweep skipped)" if args.fast else "(interference sweep done)")
        assemblies.main()
        part_glbs()
        print("viewer GLBs written")
    lay_path = SRC / "core_cell_layout.json"
    if layout is None or "static_interference" not in layout:
        layout = json.loads(lay_path.read_text()) if lay_path.exists() else None
    if layout and "collision_free_carriage_window_mm" in layout:
        data = ROOT / "software" / "seedforge" / "data" / "core_cell_limits.json"
        data.write_text(json.dumps({"source": "hardware/cad/source/core_cell_layout.json (generated by tools/build_cad.py)",
                                    "home_trip_x_mm": 45.0, "end_trip_x_mm": 149.0,
                                    "collision_free_carriage_window_mm": layout["collision_free_carriage_window_mm"]}, indent=2) + "\n")
    rows = qa()
    write_manifest(rows)
    write_report(rows, layout)
    bad = [r["part_id"] for r in rows if r["family"] == "machine" and not r["cad_valid"]]
    print(f"QA: {len(rows)} files, machine failures: {bad or 'none'}  ({time.time() - t0:.0f} s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
