#!/usr/bin/env python3
"""Generate BOM views from tools/bom_source.py and the CAD manifest.

Outputs (hardware/bom/):
  master_bom.csv                 every purchased item
  A_minimum_demonstrator.csv     view A
  B_manufacturing_bench.csv      views A + B
  C_optional_deployment.csv      view C
  printed_parts.csv              from hardware/cad/manifest.csv (active machine parts)
  BOM.md                         human-readable summary with totals
  website/public/data/bom.json   for the site
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from bom_source import COLUMNS, ROWS  # noqa: E402

OUT = ROOT / "hardware" / "bom"


def rows():
    out = []
    for r in ROWS:
        d = dict(zip(COLUMNS, r))
        d["est_total_usd"] = round(float(d["est_unit_usd"]) * int(d["qty"]), 2)
        out.append(d)
    return out


def write(path, items, cols):
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, lineterminator="\n")
        w.writeheader()
        for it in items:
            w.writerow({k: it.get(k, "") for k in cols})


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    items = sorted(rows(), key=lambda i: (i["item_id"][0], int(i["item_id"][1:])))
    cols = COLUMNS[:10] + ["est_total_usd"] + COLUMNS[10:]
    ids = [i["item_id"] for i in items]
    assert len(ids) == len(set(ids)), "duplicate item ids"
    write(OUT / "master_bom.csv", items, cols)
    views = {"A": [i for i in items if i["view"] == "A"], "B": [i for i in items if i["view"] in "AB"],
             "C": [i for i in items if i["view"] == "C"]}
    write(OUT / "A_minimum_demonstrator.csv", views["A"], cols)
    write(OUT / "B_manufacturing_bench.csv", views["B"], cols)
    write(OUT / "C_optional_deployment.csv", views["C"], cols)

    printed = []
    man = ROOT / "hardware" / "cad" / "manifest.csv"
    if man.exists():
        for r in csv.DictReader(man.open()):
            if r["family"] == "machine":
                printed.append(r)
        pcols = ["part_id", "file_stem", "module", "status", "qty", "material", "bbox_x_mm", "bbox_y_mm", "bbox_z_mm",
                 "volume_cm3", "solid_mass_petg_g", "cad_valid", "source", "notes"]
        write(OUT / "printed_parts.csv", printed, pcols)

    def total(v, owned=False):
        return sum(i["est_total_usd"] for i in v if i["ownership"] == "buy" or (owned and i["ownership"] == "owned"))

    tA, tB, tC = total(views["A"]), total(views["B"]), total(views["C"])
    fA, fB, fC = total(views["A"], True), total(views["B"], True), total(views["C"], True)
    payload = sum(i["est_total_usd"] for i in views["C"] if i["module"] == "M10 payload" and i["ownership"] == "buy")
    core_prints = [p for p in printed if p["status"] == "core"]
    core_g = sum(float(p["solid_mass_petg_g"]) * int(p["qty"] or 1) for p in core_prints)
    md = ["# Bill of materials", "",
          "Generated by `python tools/build_bom.py` from `tools/bom_source.py`. Prices are planning estimates (USD, October 2026,",
          "budget generic parts, before tax and shipping), not quotations. 'owned' items count only in the buying-everything",
          "column; 'optional' items are not needed for that view and are not counted. Every fastener is M2 (item A37).",
          "Links appear only where the product page or ID was confirmed by search on 2026-10-11.", "",
          f"| view | scope | items | to buy if you own the 'owned' parts (USD) | buying everything (USD) |", "|---|---|---|---|---|",
          f"| A | Minimum demonstrator: feed, tension, synchronized winding, stopping, clamp, cut, demold, vision | {len(views['A'])} | {tA:.0f} | {fA:.0f} |",
          f"| A+B | Complete manufacturing bench: adds tails, drying, seed handling, tip forming, final QA, XY transfer | {len(views['B'])} | {tB:.0f} | {fB:.0f} |",
          f"| C | Optional deployment system incl. a budget ArduPilot quad (downstream; not required for manufacturing) | {len(views['C'])} | {tC:.0f} | {fC:.0f} |",
          f"| C payload only | Cassette electronics if an ArduPilot aircraft is already available | - | {payload:.0f} | {payload:.0f} |", "",
          f"Printed parts for the core cell (status `core`): {len(core_prints)} part types, about {core_g / 1000:.2f} kg of PETG",
          "if printed solid; typical 3-4 walls and 25-40 % infill use roughly half of that.", ""]
    for key, title in (("A", "A - minimum demonstrator"), ("B", "A + B - complete manufacturing bench"),
                       ("C", "C - optional deployment")):
        md += [f"## {title}", "", "| id | qty | item | key spec | example | supplier | est. USD | status | notes |",
               "|---|---|---|---|---|---|---|---|---|"]
        for i in views[key]:
            ex = f"[{i['example_part']}]({i['verified_url']})" if i["verified_url"] else i["example_part"]
            md.append(f"| {i['item_id']} | {i['qty']} | {i['description']} | {i['key_spec']} | {ex} | {i['preferred_supplier']} / "
                      f"{i['alternative_supplier']} | {i['est_total_usd']:.2f} | {i['ownership']} | {i['notes']} {('(' + i['change_vs_r3'] + ')') if i['change_vs_r3'] else ''} |")
        md.append("")
    (OUT / "BOM.md").write_text("\n".join(md) + "\n")
    site = ROOT / "website" / "public" / "data"
    site.mkdir(parents=True, exist_ok=True)
    (site / "bom.json").write_text(json.dumps({"totals": {"A": tA, "A_plus_B": tB, "C": tC, "A_all": fA, "A_plus_B_all": fB, "C_all": fC,
                                                          "C_payload": payload}, "items": items,
                                               "printed": printed, "core_print_mass_g": core_g}, indent=1))
    print(f"BOM: A ${tA:.0f} (all ${fA:.0f}), A+B ${tB:.0f} (all ${fB:.0f}), C ${tC:.0f} (all ${fC:.0f}), payload ${payload:.0f}; "
          f"{len(printed)} printed part types")


if __name__ == "__main__":
    main()
