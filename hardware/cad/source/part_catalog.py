PARTS: dict[str, dict] = {}


def _load():
    r3 = json.loads(R3_MANIFEST.read_text()) if R3_MANIFEST.exists() else []
    for p in r3:
        pid = p["id"]
        stem = f"{pid}_{p['name']}"
        module = MODULE_OVERRIDE.get(pid, MODULE_OF_PREFIX.get(pid[0], "?"))
        status, extra = STATUS_OVERRIDE.get(pid, ("active", ""))
        if status == "active":
            status = "core" if module in ("M1", "M2", "M3", "M7", "C", "Z") else "upcoming"
        PARTS[stem] = {"id": pid, "module": module, "qty": p["qty"], "material": p["material"], "status": status,
                       "source": "R3 STEP + M2 conversion", "notes": (extra + " " + p.get("notes", "")).strip(),
                       "orientation": p.get("orientation", "")}
    from core_cell import NEW_PARTS
    for pid, (stem, module, qty, mat) in NEW.items():
        derived = pid in ("F09", "F10")
        PARTS[stem] = {"id": pid, "module": module, "qty": qty, "material": mat, "status": "core",
                       "source": "derived from R3 STEP in core_cell.py" if derived else "R3.1 core_cell.py",
                       "notes": NEW_PARTS[stem][4], "orientation": ""}


def catalog_row(stem: str, family: str) -> dict:
    if not PARTS:
        _load()
    if family == "reference":
        pid = stem.split("_")[0]
        status = "experimental print" if pid == "MR02" else ("demo print" if pid == "PR24" else "reference")
        return {"id": pid, "module": "reference", "qty": "", "material": "metal (buy)" if pid in ("MR01", "MR05") else "",
                "status": status, "source": "paper_reference.py",
                "notes": "Reference/clearance geometry, not a functional carrier." if pid.startswith("PR") else "Fixture/fit reference."}
    if stem not in PARTS:
        return {"id": stem.split("_")[0], "module": "?", "qty": "", "material": "", "status": "unknown", "source": "?", "notes": ""}
    return PARTS[stem]


_load()
