"""Deterministic vision QA command line.

    python -m seedforge.vision demo --out datasets/synthetic
        generate the labelled synthetic set, inspect every image, write
        annotated overlays and a confusion-matrix report (report.json/.md)

    python -m seedforge.vision inspect IMAGE [--px-per-mm 40 --pitch 5 --turns 7 --width 2.5]
        inspect one image, print the verdict, write IMAGE_qa.png

    python -m seedforge.vision evaluate DIR
        score a labelled directory (IMAGE.png + IMAGE.json with "label")
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cv2

from .pipeline import Thresholds, inspect, overlay
from .synth import standard_set, write_set

EXPECTED_EVENT = {"good": "VISION_OK", "gap": "FAULT_GAP", "overlap": "FAULT_OVERLAP", "length": "FAULT_LENGTH",
                  "deformed": "FAULT_LENGTH"}


def thresholds_from(args) -> Thresholds:
    return Thresholds(px_per_mm=args.px_per_mm, expected_pitch_mm=args.pitch, expected_turns=args.turns,
                      strip_w_mm=args.width, strip_t_mm=args.thickness, mandrel_d_mm=args.mandrel,
                      max_gap_mm=args.max_gap, max_overlap_mm=args.max_overlap)


def evaluate(directory: Path, th: Thresholds, write_overlays: bool = True) -> dict:
    rows = []
    for img_path in sorted(directory.glob("*.png")):
        if img_path.stem.endswith("_qa"):
            continue
        meta_path = img_path.with_suffix(".json")
        if not meta_path.exists():
            continue
        label = json.loads(meta_path.read_text()).get("label", "good")
        img = cv2.imread(str(img_path), cv2.IMREAD_GRAYSCALE)
        res = inspect(img, th)
        if write_overlays:
            cv2.imwrite(str(img_path.with_name(img_path.stem + "_qa.png")), overlay(img, res))
        rows.append({"image": img_path.name, "label": label, "expected": EXPECTED_EVENT.get(label, "VISION_OK"),
                     **res.summary()})
    tp = sum(1 for r in rows if r["label"] == "good" and r["ok"])          # true accept
    tn = sum(1 for r in rows if r["label"] != "good" and not r["ok"])      # true reject
    fa = sum(1 for r in rows if r["label"] != "good" and r["ok"])          # false accept (escape)
    fr = sum(1 for r in rows if r["label"] == "good" and not r["ok"])      # false reject
    right_reason = sum(1 for r in rows if r["label"] != "good" and r["event"] == r["expected"])
    report = {"data": "SYNTHETIC images - not validation evidence for real veneer",
              "n": len(rows), "true_accept": tp, "true_reject": tn, "false_accept": fa, "false_reject": fr,
              "rejects_with_expected_fault_code": right_reason, "thresholds": th.__dict__, "rows": rows}
    return report


def write_report(report: dict, out: Path) -> None:
    (out / "report.json").write_text(json.dumps(report, indent=2, default=float))
    lines = ["# Vision QA - synthetic evaluation", "",
             "> SYNTHETIC images generated by `seedforge.vision.synth`. These numbers test the software, "
             "not the machine. Phase 6 requires a labelled set of real images.", "",
             "| | predicted accept | predicted reject |", "|---|---|---|",
             f"| labelled good | {report['true_accept']} (true accept) | {report['false_reject']} (false reject) |",
             f"| labelled defective | {report['false_accept']} (false accept) | {report['true_reject']} (true reject) |", "",
             f"Rejects carrying the expected fault code: {report['rejects_with_expected_fault_code']} of "
             f"{report['n'] - report['true_accept'] - report['false_reject']}", "",
             "| image | label | event | pitch mm | turns | max gap mm | overlap est mm | sag mm |",
             "|---|---|---|---|---|---|---|---|"]
    for r in report["rows"]:
        f = lambda v: "-" if v is None else f"{v:.2f}"  # noqa: E731
        lines.append(f"| {r['image']} | {r['label']} | {r['event']} | {f(r['pitch_mm'])} | {f(r['turns'])} | "
                     f"{f(r['max_gap_mm'])} | {f(r['overlap_est_mm'])} | {f(r['axis_sag_mm'])} |")
    (out / "report.md").write_text("\n".join(lines) + "\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m seedforge.vision", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("demo", "inspect", "evaluate"):
        p = sub.add_parser(name)
        if name == "inspect":
            p.add_argument("image")
        if name == "evaluate":
            p.add_argument("directory")
        if name == "demo":
            p.add_argument("--out", default="datasets/synthetic")
        p.add_argument("--px-per-mm", type=float, default=40.0)
        p.add_argument("--pitch", type=float, default=5.0)
        p.add_argument("--turns", type=float, default=7.0)
        p.add_argument("--width", type=float, default=2.5)
        p.add_argument("--thickness", type=float, default=0.5)
        p.add_argument("--mandrel", type=float, default=0.8)
        p.add_argument("--max-gap", type=float, default=1.6)
        p.add_argument("--max-overlap", type=float, default=0.4)
    args = ap.parse_args(argv)
    th = thresholds_from(args)

    if args.cmd == "inspect":
        img = cv2.imread(args.image, cv2.IMREAD_UNCHANGED)
        res = inspect(img, th)
        print(json.dumps(res.summary(), indent=2, default=float))
        if img is not None:
            out = Path(args.image).with_name(Path(args.image).stem + "_qa.png")
            cv2.imwrite(str(out), overlay(img, res))
            print(f"overlay: {out}")
        return 0 if res.ok else 2
    if args.cmd == "demo":
        out = Path(args.out)
        write_set(out, standard_set(args.px_per_mm))
        rep = evaluate(out, th)
    else:
        out = Path(args.directory)
        rep = evaluate(out, th)
    write_report(rep, out)
    print(f"{rep['n']} images: true accept {rep['true_accept']}, true reject {rep['true_reject']}, "
          f"false accept {rep['false_accept']}, false reject {rep['false_reject']}  ({rep['data']})")
    print(f"report: {out / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
